import { test, expect } from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";

const accounts: Record<string, {email: string; password: string}> = JSON.parse(process.env.KLTN_E2E_ACCOUNTS_JSON || "{}");
const api = `http://127.0.0.1:${process.env.KLTN_E2E_API_PORT || "8001"}/api/v1`;

test("Excel GV: xem trước → tạo riêng, chưa gửi → chọn/bỏ chọn → gửi riêng từng người → kích hoạt thật", async ({browser}) => {
  const admin = await browser.newContext();
  const page = await admin.newPage();
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const outbox = path.join(process.env.KLTN_E2E_RUN_DIR!, "mail-outbox");
  const messages = async () => fs.readdir(outbox).catch(() => [] as string[]);
  let lecturer: Awaited<ReturnType<typeof browser.newContext>> | undefined;
  try {
    await page.goto("/");
    await page.getByLabel("Email", {exact: true}).fill(accounts.admin.email);
    await page.getByLabel("Mật khẩu", {exact: true}).fill(accounts.admin.password);
    await page.getByRole("button", {name: "Đăng nhập", exact: true}).click();
    await expect(page.getByRole("heading", {name: "Tổng quan", exact: true})).toBeVisible();
    await page.goto("/lecturers?tab=activation");
    const region = page.getByRole("region", {name: "Nhập và mời danh sách giảng viên"});
    await expect(region.getByRole("heading", {name: "Nhập danh sách giảng viên bằng Excel"})).toBeVisible();
    const downloadPromise = page.waitForEvent("download");
    await region.getByRole("button", {name: "Tải Excel mẫu GV"}).click();
    const download = await downloadPromise;
    const file = path.join(process.env.KLTN_E2E_RUN_DIR!, "lecturer-import.xlsx");
    await download.saveAs(file);
    const before = new Set(await messages());
    await region.getByLabel("Tệp danh sách GV").setInputFiles({name: "invalid.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: Buffer.from("invalid Excel")});
    await region.getByRole("button", {name: "Xem trước danh sách GV"}).click();
    await expect(region.getByRole("alert").filter({hasText: "Không đọc được danh sách GV"})).toBeVisible();
    await region.getByLabel("Tệp danh sách GV").setInputFiles(file);
    await region.getByRole("button", {name: "Xem trước danh sách GV"}).click();
    await expect(region.getByText(/Kết quả xem trước: 3\/3 dòng hợp lệ/)).toBeVisible();
    const create = region.getByRole("button", {name: "Xác nhận tạo tài khoản GV"});
    await expect(create).toBeDisabled();
    await region.getByLabel(/Tôi đã đối chiếu danh sách/).check();
    await create.click();
    await expect(region.getByText(/Đã tạo 3 tài khoản GV chờ kích hoạt. Chưa gửi email/)).toBeVisible();
    expect((await messages()).filter(name => !before.has(name))).toHaveLength(0);
    await region.getByLabel("Tìm GV để gửi link").fill("DEMO-GV-");
    await expect(region.getByRole("row")).toHaveCount(4);
    const selectAll = region.getByLabel(/Chọn tất cả GV có thể gửi trong kết quả tìm kiếm/);
    await region.getByRole("button", {name: "Chọn tất cả GV có thể gửi", exact: true}).click();
    await expect(region.getByRole("button", {name: "Gửi link cho GV đã chọn (3)", exact: true})).toBeEnabled();
    await region.getByRole("button", {name: "Bỏ chọn tất cả", exact: true}).click();
    await expect(region.getByRole("button", {name: "Gửi link cho GV đã chọn (0)", exact: true})).toBeDisabled();
    await selectAll.check();
    await expect(region.getByRole("button", {name: "Gửi link cho GV đã chọn (3)", exact: true})).toBeEnabled();
    await selectAll.uncheck();
    await expect(region.getByRole("button", {name: "Gửi link cho GV đã chọn (0)", exact: true})).toBeDisabled();
    await selectAll.check();
    await region.getByRole("checkbox", {name: "Chọn GV DEMO-GV-002", exact: true}).uncheck();
    await region.getByRole("button", {name: "Gửi link cho GV đã chọn (2)", exact: true}).click();
    await expect(region.getByText("Đã xử lý 2 người: 2 gửi thành công, 0 chưa gửi được. Xem kết quả từng dòng.")).toBeVisible();
    const row1 = region.getByRole("row").filter({hasText: "DEMO-GV-001"});
    const row2 = region.getByRole("row").filter({hasText: "DEMO-GV-002"});
    await expect(row1.getByText("Đã lưu thư thử nghiệm", {exact: true})).toBeVisible();
    await expect(row2.getByText("Chưa ghi nhận gửi link", {exact: true})).toBeVisible();
    const sentFiles = (await messages()).filter(name => !before.has(name));
    expect(sentFiles).toHaveLength(2);
    const contents = await Promise.all(sentFiles.map(name => fs.readFile(path.join(outbox, name), "utf8")));
    expect(contents.some(text => text.startsWith("To: gv02@demo.test"))).toBe(false);
    const activationMail = contents.find(text => text.startsWith("To: gv01@demo.test"))!;
    expect(activationMail).toBeTruthy();
    expect(activationMail).toContain("Xin chào giảng viên Lê Quang Huy");
    expect(activationMail).toContain("Email đăng nhập: gv01@demo.test");
    expect(activationMail).toContain("Đây là liên kết kích hoạt tài khoản giảng viên của bạn");
    await row2.getByRole("button", {name: "Gửi link cho DEMO-GV-002", exact: true}).click();
    await expect(region.getByText("Đã xử lý 1 người: 1 gửi thành công, 0 chưa gửi được. Xem kết quả từng dòng.")).toBeVisible();
    await page.reload();
    await region.getByLabel("Tìm GV để gửi link").fill("DEMO-GV-");
    await expect(region.getByText("Đã lưu thư thử nghiệm", {exact: true})).toHaveCount(3);
    await region.screenshot({path: path.join(process.env.KLTN_E2E_RUN_DIR!, "lecturer-import-ui.png")});

    const activationUrl = activationMail.match(/http[^\s]+\/account\/activate\?token=[^\s]+/)![0];
    lecturer = await browser.newContext();
    const activated = await lecturer.newPage();
    await activated.goto(activationUrl);
    await activated.getByLabel("Mật khẩu mới", {exact: true}).fill("Synthetic-GV-password-2026!");
    await activated.getByLabel("Nhập lại mật khẩu", {exact: true}).fill("Synthetic-GV-password-2026!");
    await activated.getByRole("button", {name: "Lưu mật khẩu"}).click();
    await expect(activated.getByText("Đã cập nhật mật khẩu. Bạn có thể đăng nhập.")).toBeVisible();
    await activated.getByRole("link", {name: "Quay lại đăng nhập"}).click();
    await activated.getByLabel("Email", {exact: true}).fill("gv01@demo.test");
    await activated.getByLabel("Mật khẩu", {exact: true}).fill("Synthetic-GV-password-2026!");
    await activated.getByRole("button", {name: "Đăng nhập", exact: true}).click();
    await expect(activated.getByRole("heading", {name: "Tổng quan", exact: true})).toBeVisible();
    const identity = await lecturer.request.get(api + "/me/context");
    expect((await identity.json()).lecturer_code).toBe("DEMO-GV-001");
    expect((await lecturer.request.get(api + "/admin/lecturers")).status()).toBe(403);
    await page.reload();
    await region.getByLabel("Chỉ hiển thị GV chưa kích hoạt").uncheck();
    await region.getByLabel("Tìm GV để gửi link").fill("DEMO-GV-001");
    await expect(region.getByText("Đã kích hoạt", {exact: true})).toBeVisible();
    await expect(region.getByRole("checkbox", {name: "Chọn GV DEMO-GV-001", exact: true})).toBeDisabled();
    await region.getByLabel("Tệp danh sách GV").setInputFiles(file);
    await region.getByRole("button", {name: "Xem trước danh sách GV"}).click();
    await expect(region.getByText(/Kết quả xem trước: 0\/3 dòng hợp lệ/)).toBeVisible();
    await expect(region.getByText("Email đã thuộc một tài khoản trong hệ thống.", {exact: true})).toHaveCount(3);
    await expect(region.getByRole("button", {name: "Xác nhận tạo tài khoản GV"})).toBeDisabled();
    expect(errors).toEqual([]);
  } finally {
    await lecturer?.close();
    await admin.close();
  }
});
