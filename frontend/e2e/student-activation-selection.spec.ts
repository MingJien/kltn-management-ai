import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

const accounts: Record<string,{email:string;password:string}> = JSON.parse(process.env.KLTN_E2E_ACCOUNTS_JSON || '{}');
const outbox = path.join(process.env.KLTN_E2E_RUN_DIR!, 'mail-outbox');
const files = async () => fs.readdir(outbox).catch(()=>[] as string[]);

test('Admin chọn SV gửi link sau import, SV vẫn tự yêu cầu được', async ({browser}) => {
  const admin = await browser.newContext();
  const student = await browser.newContext();
  const page = await admin.newPage();
  try {
    await page.goto('/');
    await page.getByLabel('Email',{exact:true}).fill(accounts.admin.email);
    await page.getByLabel('Mật khẩu',{exact:true}).fill(accounts.admin.password);
    await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Tổng quan',exact:true})).toBeVisible();
    await page.goto('/administration');
    await page.getByRole('combobox',{name:'Đợt',exact:true}).selectOption({label:'SYN-DEMO · OPEN'});
    await page.getByLabel('Nhiệm vụ').selectOption('ELIGIBILITY_IMPORTER');
    await page.getByRole('combobox',{name:'Người được giao',exact:true}).selectOption({label:accounts.admin.email});
    await page.getByLabel('Căn cứ phân công').fill('SYNTHETIC-E2E');
    await page.getByRole('button',{name:'Lưu phân công'}).click();
    await page.goto('/roster');
    await page.getByRole('tab',{name:/Nhập danh sách/}).click();
    const csv=['MSSV;Họ và tên;Email;Mã bộ môn;Lớp;Mã ngành',
      'E2E-SEL-01;Sinh viên giả 1;select01@example.invalid;SYN-DEMO-DEP;CNTT-E2E;7480201',
      'E2E-SEL-02;Sinh viên giả 2;select02@example.invalid;SYN-DEMO-DEP;CNTT-E2E;7480201',
      'E2E-SEL-03;Sinh viên giả 3;select03@example.invalid;SYN-DEMO-DEP;CNTT-E2E;7480201'].join('\n');
    const before=new Set(await files());
    await page.locator('input[type="file"]').setInputFiles({name:'students.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
    await page.getByLabel('Mã/số văn bản nguồn').fill('SYNTHETIC-E2E');
    await page.getByRole('button',{name:'Kiểm tra tệp'}).click();
    await expect(page.getByRole('heading',{name:/Xem trước: 3 sinh viên/})).toBeVisible();
    await page.getByRole('button',{name:'Nhập sau khi kiểm'}).click();
    await expect(page.getByText(/Đã ghi nhận 3 sinh viên đủ điều kiện/)).toBeVisible();
    expect((await files()).filter(name=>!before.has(name))).toHaveLength(0);
    await page.getByRole('searchbox',{name:'Tìm sinh viên',exact:true}).fill('E2E-SEL-');
    const first=page.getByRole('checkbox',{name:'Chọn SV E2E-SEL-01'});
    const second=page.getByRole('checkbox',{name:'Chọn SV E2E-SEL-02'});
    await expect(first).toBeEnabled();
    await page.getByRole('button',{name:/Chọn tất cả có thể gửi/}).click();
    await expect(first).toBeChecked(); await expect(second).toBeChecked();
    await page.getByRole('button',{name:'Bỏ chọn tất cả'}).click();
    await expect(first).not.toBeChecked(); await expect(second).not.toBeChecked();
    const sv=await student.newPage();
    await sv.goto('/account/activation-request');
    await sv.getByLabel('MSSV hoặc mã giảng viên').fill('E2E-SEL-01');
    await sv.getByLabel('Email đã đăng ký').fill('select01@example.invalid');
    await sv.getByRole('button',{name:'Gửi hướng dẫn'}).click();
    await expect(sv.getByText(/Nếu thông tin hợp lệ/)).toBeVisible();
    let selfMail='';
    await expect.poll(async()=>{for(const f of await files()){const text=await fs.readFile(path.join(outbox,f),'utf8');if(text.startsWith('To: select01@example.invalid')) selfMail=text;}return selfMail;}).toContain('/account/activate?token=');
    expect(selfMail).toContain('Xin chào sinh viên Sinh viên giả 1');
    expect(selfMail).toContain('Đây là liên kết kích hoạt tài khoản sinh viên của bạn');
    expect(selfMail).toContain('Email đăng nhập: select01@example.invalid');
    const beforeAdminSend = new Set(await files());
    await first.check(); await second.check();
    await page.getByRole('button',{name:'Gửi link đã chọn (2)'}).click();
    await expect(page.getByText(/Đã xử lý 2 sinh viên: 2 yêu cầu gửi thành công/)).toBeVisible();
    await expect(page.getByRole('row').filter({hasText:'E2E-SEL-01'})).toContainText('Đã lưu thư thử nghiệm trên máy');
    const adminFiles=(await files()).filter(f=>!beforeAdminSend.has(f));
    const adminMessages=await Promise.all(adminFiles.map(f=>fs.readFile(path.join(outbox,f),'utf8')));
    const staffMail=adminMessages.find(text=>text.startsWith('To: select01@example.invalid'))!;
    expect(staffMail).toContain('Đây là liên kết kích hoạt tài khoản sinh viên của bạn');
    expect(staffMail).toContain('Xin chào sinh viên Sinh viên giả 1');
    expect(staffMail).toContain('Email đăng nhập: select01@example.invalid');
    const selfUrl=selfMail.match(/http[^\s]+\/account\/activate\?token=[^\s]+/)![0];
    await sv.goto(selfUrl);
    await sv.getByLabel('Mật khẩu mới',{exact:true}).fill('Synthetic-Password-2026!');
    await sv.getByLabel('Nhập lại mật khẩu',{exact:true}).fill('Synthetic-Password-2026!');
    await sv.getByRole('button',{name:'Lưu mật khẩu'}).click();
    await expect(sv.getByText('Đã cập nhật mật khẩu. Bạn có thể đăng nhập.')).toBeVisible();
    await page.getByRole('row').filter({hasText:'E2E-SEL-03'}).getByRole('button',{name:'Gửi link',exact:true}).click();
    await expect(page.getByText(/Đã xử lý 1 sinh viên: 1 yêu cầu gửi thành công/)).toBeVisible();
    // Actual UI: restore requires a new decision; it is distinct from account lock.
    await page.goto('/administration');
    await page.getByRole('combobox',{name:'Đợt',exact:true}).selectOption({label:'SYN-DEMO · OPEN'});
    await page.getByLabel('Nhiệm vụ').selectOption('ELIGIBILITY_VERIFIER');
    await page.getByRole('combobox',{name:'Người được giao',exact:true}).selectOption({label:accounts.admin.email});
    await page.getByLabel('Căn cứ phân công').fill('SYNTHETIC-REVIEW');
    await page.getByRole('button',{name:'Lưu phân công'}).click();
    await expect(page.getByText('Đã lưu phân công.',{exact:true})).toBeVisible();
    await page.goto('/roster');
    await page.getByText('Thu hồi kết quả đã xác nhận',{exact:true}).click();
    await page.getByRole('combobox',{name:'Sinh viên cần thu hồi',exact:true}).selectOption({label:'E2E-SEL-01 · Sinh viên giả 1'});
    await page.getByLabel('Văn bản nguồn thu hồi').fill('SYNTHETIC-REVOKE');
    await page.getByLabel('Lý do',{exact:true}).fill('Thu hồi thử nghiệm có căn cứ');
    await page.getByRole('button',{name:'Thu hồi quyền tham gia',exact:true}).click();
    await expect(page.getByText('Đã thu hồi quyền tham gia; hồ sơ cũ được giữ để rà soát.')).toBeVisible();
    await sv.goto('/');
    await sv.getByLabel('Email',{exact:true}).fill('select01@example.invalid');
    await sv.getByLabel('Mật khẩu',{exact:true}).fill('Synthetic-Password-2026!');
    await sv.getByRole('button',{name:'Đăng nhập',exact:true}).click();
    await expect(sv.getByRole('heading',{name:'Tổng quan',exact:true})).toBeVisible();
    await page.getByText('Khôi phục quyền tham gia đã thu hồi',{exact:true}).click();
    await page.getByRole('combobox',{name:'Sinh viên cần khôi phục',exact:true}).selectOption({label:'E2E-SEL-01 · Sinh viên giả 1'});
    await page.getByLabel('Văn bản/căn cứ khôi phục').fill('SYNTHETIC-RESTORE');
    await page.getByLabel('Lý do khôi phục').fill('Khoa xác nhận lại điều kiện thử nghiệm');
    await page.getByRole('button',{name:'Khôi phục quyền tham gia',exact:true}).click();
    await expect(page.getByText('Đã khôi phục quyền tham gia; lịch sử cũ được giữ.')).toBeVisible();
    await page.goto('/administration');
    await page.getByLabel('Trạng thái tài khoản',{exact:true}).selectOption('PENDING');
    await page.getByRole('textbox',{name:'Tìm theo mã, tên hoặc email tài khoản'}).fill('select02@example.invalid');
    await expect(page.locator('.account-list__row').filter({hasText:'select02@example.invalid'})).toContainText('Chờ kích hoạt');
    await page.getByLabel('Trạng thái tài khoản',{exact:true}).selectOption('ALL');
    await page.getByRole('textbox',{name:'Tìm theo mã, tên hoặc email tài khoản'}).fill('select01@example.invalid');
    const accountRow=page.locator('.account-list__row').filter({hasText:'select01@example.invalid'});
    await expect(accountRow).toContainText('Sinh viên giả 1');
    await page.getByLabel('Lý do thao tác tài khoản').fill('Khóa tài khoản thử nghiệm');
    await accountRow.getByRole('button',{name:'Khóa',exact:true}).click();
    await expect(accountRow).toContainText('Bị khóa');
    await sv.reload();
    await expect(sv.getByRole('button',{name:'Đăng nhập',exact:true})).toBeVisible();
    await sv.getByLabel('Email',{exact:true}).fill('select01@example.invalid');
    await sv.getByLabel('Mật khẩu',{exact:true}).fill('Synthetic-Password-2026!');
    await sv.getByRole('button',{name:'Đăng nhập',exact:true}).click();
    await expect(sv.getByRole('button',{name:'Đăng nhập',exact:true})).toBeVisible();
    await expect(sv.getByLabel('Mật khẩu',{exact:true})).toHaveValue('');
    await accountRow.getByRole('button',{name:'Mở khóa',exact:true}).click();
    await expect(accountRow).toContainText('Hoạt động');
    await sv.getByLabel('Mật khẩu',{exact:true}).fill('Synthetic-Password-2026!');
    await sv.getByRole('button',{name:'Đăng nhập',exact:true}).click();
    await expect(sv.getByRole('heading',{name:'Tổng quan',exact:true})).toBeVisible();
  } finally {await student.close();await admin.close();}
});
